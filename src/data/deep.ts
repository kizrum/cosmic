/**
 * Beyond the planets: the heliosphere, spacecraft leaving the Solar System, the Oort cloud,
 * the nearest stars and the Milky Way. Russian is the source text (see data/en/deep.ts).
 */
export type DeepRealm = 'local' | 'galaxy';

export interface DeepDef {
  id: string;
  realm: DeepRealm;
  name: string;
  latin: string;
  kind: string;
  color: string;
  description: string;
  facts: [string, string][];
  /** Caveat shown under the description (models, reconstructions). */
  note?: string;
}

/** Stops of the zoom beyond the planets, widest first (the breadcrumbs above the Solar System). */
export type Level = 'galaxy' | 'stars' | 'helio';
export const LEVELS: Level[] = ['galaxy', 'stars', 'helio'];
export const LEVEL_NAMES: Record<Level, string> = { galaxy: 'Млечный Путь', stars: 'Окрестности Солнца', helio: 'Гелиосфера' };
/** The object whose panel describes a level. */
export const LEVEL_PANEL: Record<Level, string> = { galaxy: 'milkyway', stars: 'neighbourhood', helio: 'heliosphere' };
const PROBES = ['voyager1', 'voyager2', 'pioneer10', 'pioneer11', 'newHorizons'];

/** Level an object is seen at (its breadcrumbs): a deep id or `star:<Gliese id>`. */
export function levelOf(id: string): Level {
  if (id.startsWith('star:')) return 'stars';
  if (id === 'heliosphere' || PROBES.includes(id)) return 'helio';
  return deepById(id).realm === 'galaxy' ? 'galaxy' : 'stars';
}

