/**
 * Editorial profile of an object for the info panel: its place in the system, a one-line
 * hook, a curious fact and the history of its exploration. Russian is the source; the
 * English overlay lives in ./en/profiles.ts. Every field is optional in the panel.
 */
export interface Milestone {
  /** Year or date, as shown. */
  when: string;
  name: string;
  note: string;
}

export interface Profile {
  /** Place in the system, shown after the kind: «4-я планета от Солнца». */
  place?: string;
  /** One sentence: why this object is interesting. */
  tagline: string;
  /** "Curious" card on the overview. */
  fun?: string;
  /** Discovery and exploration, oldest first. */
  history?: Milestone[];
}

