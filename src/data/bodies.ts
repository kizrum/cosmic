import type { ElementSource } from '../astro';
import { DWARFS, SATELLITES } from './satellites';

export interface Site {
  id: string;
  name: string;
  kind: string;
  lat: number;
  lon: number;
  /** Radius multiplier for features above the surface (e.g. ring gaps). Default 1. */
  elevation?: number;
  description: string;
  facts?: [string, string][];
}

export type BodyGroup = 'star' | 'planet' | 'moon' | 'dwarf';

export interface BodyDef {
  id: string;
  name: string;
  /** Russian genitive of the name ("до Марса"), for bodies with moons. Defaults to `name`. */
  genitive?: string;
  latin: string;
  kind: string;
  group: BodyGroup;
  parent?: string;
  radiusKm: number;
  /** Polar flattening (1 - polar/equatorial). */
  flattening?: number;
  /** Triaxial semi-axes in km (a toward the prime meridian, b, c polar). */
  shape?: [number, number, number];
  /** Heliocentric orbit (planets, dwarf planets) or planetocentric (moons, km). */
  orbit?: ElementSource;
  /** IAU pole (J2000 RA/Dec, degrees; optional rates per century). Omitted: orbit normal. */
  pole?: { ra: number; dec: number; raRate?: number; decRate?: number };
  /** Prime meridian W = W0 + Wdot·d (degrees, d = days from J2000). */
  W0?: number;
  Wdot?: number;
  /** Synchronous rotation: longitude 0 always faces the parent body. */
  locked?: boolean;
  /** Surface map in public/textures. */
  texture?: string;
  color: string;
  facts: [string, string][];
  description: string;
  /** Caveat about data quality shown in the panel. */
  note?: string;
  sites: Site[];
}

const planetOrbit = (j2000: number[], rates: number[], period: number): ElementSource => {
  const [a, e, i, L, peri, node] = j2000;
  const [ra, re, ri, rL, rp, rn] = rates;
  return { kind: 'planet', el: { a, e, i, L, peri, node, period, rates: { a: ra, e: re, i: ri, L: rL, peri: rp, node: rn } } };
};

