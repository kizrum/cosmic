/**
 * Trajectories of the spacecraft leaving the Solar System, from JPL Horizons:
 * run with `npm run fetch:probes` (needs network). Writes src/data/probeTracks.ts.
 *
 * Heliocentric positions (ecliptic J2000, AU), every 10 days through the planetary flybys,
 * every 180 days afterwards, up to the end of each ephemeris. Past that the app
 * extrapolates linearly: on an escape trajectory far from the planets the speed is constant
 * to a fraction of a per cent over decades.
 */
import { writeFileSync } from 'node:fs';

const API = 'https://ssd.jpl.nasa.gov/api/horizons.api';
const J2000_JD = 2451545.0;

/** Horizons id, and the year after which the cruise needs no dense sampling (last flyby + 1). */
const PROBES: Record<string, { command: string; denseUntil: number }> = {
  pioneer10: { command: '-23', denseUntil: 1975 },
  pioneer11: { command: '-24', denseUntil: 1981 },
  voyager1: { command: '-31', denseUntil: 1982 },
  voyager2: { command: '-32', denseUntil: 1990 },
  newHorizons: { command: '-98', denseUntil: 2016 },
};

const jd = (iso: string) => J2000_JD + (Date.parse(iso) - Date.UTC(2000, 0, 1, 12)) / 86_400_000;
const isoOfJd = (j: number) => new Date(Date.UTC(2000, 0, 1, 12) + (j - J2000_JD) * 86_400_000).toISOString().slice(0, 16).replace('T', ' ');

async function query(command: string, start: string, stop: string, step: string) {
  const params = new URLSearchParams({
    format: 'json', COMMAND: `'${command}'`, EPHEM_TYPE: 'VECTORS', CENTER: `'500@10'`,
    START_TIME: `'${start}'`, STOP_TIME: `'${stop}'`, STEP_SIZE: `'${step}'`,
    REF_PLANE: 'ECLIPTIC', REF_SYSTEM: 'ICRF', VEC_TABLE: '1', OUT_UNITS: 'AU-D', CSV_FORMAT: 'YES',
  });
  const { result } = (await (await fetch(`${API}?${params}`)).json()) as { result: string };
  return result;
}

/** First and last instants Horizons can serve for a target (taken from its error messages). */
async function span(command: string) {
  const parse = (r: string, word: string) => {
    const m = r.match(new RegExp(`${word} A\\.D\\. (\\d{4})-([A-Z]{3})-(\\d{2}) (\\d{2}:\\d{2})`));
    if (!m) return null;
    const mon = 'JANFEBMARAPRMAYJUNJULAUGSEPOCTNOVDEC'.indexOf(m[2]) / 3 + 1;
    return `${m[1]}-${String(mon).padStart(2, '0')}-${m[3]}T${m[4]}Z`;
  };
  const first = parse(await query(command, '1960-01-01', '1960-01-02', '1d'), 'prior to');
  const last = parse(await query(command, '2199-01-01', '2199-01-02', '1d'), 'after');
  if (!first || !last) throw new Error(`${command}: cannot read the ephemeris span`);
  // Stay a day inside both ends.
  return { first: jd(first) + 1, last: jd(last) - 1 };
}

async function samples(command: string, from: number, to: number, stepDays: number) {
  const r = await query(command, isoOfJd(from), isoOfJd(to), `${stepDays}d`);
  const body = r.split('$$SOE')[1]?.split('$$EOE')[0];
  if (!body) throw new Error(`${command}: no ephemeris\n${r.slice(0, 1500)}`);
  return body.trim().split('\n').map((line) => {
    const c = line.split(',').map((s) => s.trim());
    return [Number(c[0]) - J2000_JD, Number(c[2]), Number(c[3]), Number(c[4])];
  });
}

const out: string[] = [];
for (const [id, p] of Object.entries(PROBES)) {
  const { first, last } = await span(p.command);
  const split = Math.min(last, jd(`${p.denseUntil}-01-01T00:00Z`));
  const dense = await samples(p.command, first, split, 10);
  const cruise = split < last ? await samples(p.command, split + 180, last, 180) : [];
  const rows = [...dense, ...cruise];
  console.log(`  ${id}: ${isoOfJd(first).slice(0, 10)} … ${isoOfJd(last).slice(0, 10)}, ${rows.length} points`);
  // Days from J2000 (1 decimal), position in AU (4 decimals: ~15 000 km).
  const flat = rows.map(([d, x, y, z]) => `${d.toFixed(1)},${x.toFixed(4)},${y.toFixed(4)},${z.toFixed(4)}`).join(',');
  out.push(`  ${id}: [${flat}],`);
}

const file = new URL('../src/data/probeTracks.ts', import.meta.url);
writeFileSync(file, `// Generated by scripts/fetch-probes.ts from JPL Horizons (${new Date().toISOString().slice(0, 10)}).
// Heliocentric ecliptic J2000 positions: flat [days from J2000, x, y, z (AU), …].
export const PROBE_TRACKS: Record<string, number[]> = {
${out.join('\n')}
};
`);
console.log('✓ src/data/probeTracks.ts');
