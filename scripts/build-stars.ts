/**
 * Nearby stars for the Solar neighbourhood view, from the HYG database v4.1
 * (CC BY-SA 4.0, https://github.com/astronexus/HYG-Database): run with
 * `npm run build:stars` after `npm run fetch:sources`. Writes src/data/stars.ts.
 *
 * Every star within 26 light years, and the stars brighter than magnitude 1.6 within
 * 60 ly as landmarks. Positions are converted from equatorial to the scene frame
 * (ecliptic J2000, see astro.ts), in light years.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const LY_PER_PC = 3.26156;
const OBLIQUITY = (23.4392911 * Math.PI) / 180;

const lines = readFileSync('textures-src/hygdata_v41.csv', 'utf8').split('\n');
const head = lines[0].split(',').map((h) => h.replace(/"/g, ''));
const col = (name: string) => head.indexOf(name);
const C = { id: col('id'), proper: col('proper'), gl: col('gl'), hip: col('hip'), dist: col('dist'), mag: col('mag'), absmag: col('absmag'), spect: col('spect'), ci: col('ci'), x: col('x'), y: col('y'), z: col('z'), bayer: col('bayer'), con: col('con') };

/** CSV with quoted fields (no embedded commas in this file's quoted values). */
const parse = (line: string) => line.split(',').map((f) => f.replace(/^"|"$/g, ''));

const out: string[] = [];
let count = 0;
for (const line of lines.slice(2)) {
  if (!line.trim()) continue;
  const f = parse(line);
  const pc = Number(f[C.dist]);
  if (!(pc > 0) || pc >= 100000) continue;
  const ly = pc * LY_PER_PC;
  const mag = Number(f[C.mag]);
  if (!(ly <= 26 || (ly <= 60 && mag < 1.6))) continue;
  // HYG x, y, z: equatorial J2000, parsecs → ecliptic → scene frame (x, z, −y), light years.
  const xe = Number(f[C.x]) * LY_PER_PC, ye = Number(f[C.y]) * LY_PER_PC, ze = Number(f[C.z]) * LY_PER_PC;
  const yc = ye * Math.cos(OBLIQUITY) + ze * Math.sin(OBLIQUITY);
  const zc = -ye * Math.sin(OBLIQUITY) + ze * Math.cos(OBLIQUITY);
  const r = (v: number) => Number(v.toFixed(3));
  const ci = f[C.ci] === '' ? null : Number(f[C.ci]);
  const name = f[C.proper] || (f[C.bayer] && f[C.con] ? `${f[C.bayer]} ${f[C.con]}` : '') || f[C.gl] || (f[C.hip] ? `HIP ${f[C.hip]}` : '');
  out.push(`  [${r(xe)}, ${r(zc)}, ${r(-yc)}, ${Number(f[C.absmag]).toFixed(2)}, ${mag.toFixed(2)}, ${ci === null ? 'null' : ci.toFixed(2)}, ${JSON.stringify(f[C.spect])}, ${JSON.stringify(name)}, ${JSON.stringify(f[C.gl])}],`);
  count++;
}

writeFileSync('src/data/stars.ts', `// Generated by scripts/build-stars.ts from the HYG database v4.1 (CC BY-SA 4.0,
// David Nash, https://github.com/astronexus/HYG-Database). This file is distributed under
// the same licence.
//
// [x, y, z (scene frame, light years from the Sun), absolute mag., apparent mag.,
//  B−V colour index (null if unknown), spectral type, catalogue name, Gliese id]
export type StarRow = [number, number, number, number, number, number | null, string, string, string];

export const STARS: StarRow[] = [
${out.join('\n')}
];
`);
console.log(`✓ ${count} stars → src/data/stars.ts`);
